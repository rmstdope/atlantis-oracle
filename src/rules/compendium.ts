/**
 * Converts the output of native/compendium.cpp (the engine's own descriptions
 * of items, monsters, skills and objects) into a Markdown appendix for the rules.
 */

export type CompendiumKind = 'monster' | 'illusion' | 'item' | 'skill' | 'object';

export interface CompendiumEntry {
  kind: CompendiumKind;
  abbr: string;
  name: string;
  level: number;
  text: string;
}

const KINDS = new Set<CompendiumKind>(['monster', 'illusion', 'item', 'skill', 'object']);

export function parseCompendium(output: string): CompendiumEntry[] {
  const entries: CompendiumEntry[] = [];
  let current: CompendiumEntry | undefined;
  for (const line of output.split('\n')) {
    if (line.startsWith('@@')) {
      const [kind, abbr = '', name = '', level = '0'] = line.slice(2).split('\t');
      current = KINDS.has(kind as CompendiumKind)
        ? { kind: kind as CompendiumKind, abbr, name, level: Number(level), text: '' }
        : undefined;
      if (current) entries.push(current);
    } else if (current && line.trim()) {
      current.text += (current.text ? '\n' : '') + line.trim();
    }
  }
  return entries.filter((e) => e.text && !/No skill report\.?$/.test(e.text));
}

const SECTIONS: [CompendiumKind, string][] = [
  ['monster', 'Monsters'],
  ['item', 'Items'],
  ['illusion', 'Illusions'],
  ['skill', 'Skills and spells'],
  ['object', 'Buildings, ships and lairs'],
];

/** Heading text; illusions are named the way the engine prints them. */
function title(e: CompendiumEntry): string {
  if (e.kind === 'illusion') return `illusory ${e.name} [I${e.abbr}]`;
  return e.abbr ? `${e.name} [${e.abbr}]` : e.name;
}

/** Skill reports start with "name [ABBR] 3: "; the heading already says that. */
const stripSkillPrefix = (text: string) => text.replace(/^[^\n]*?\[[A-Z0-9]+\] \d+:\s*/, '');

export function compendiumToMarkdown(entries: CompendiumEntry[]): string {
  const out = [
    '# Compendium',
    '',
    'Descriptions generated by the game engine for this variant, as players see them in turn reports.',
  ];
  for (const [kind, heading] of SECTIONS) {
    const ofKind = entries.filter((e) => e.kind === kind);
    if (ofKind.length === 0) continue;
    out.push('', `## ${heading}`);
    // Group by heading: skills have one entry per level; several objects share a name.
    const groups = new Map<string, CompendiumEntry[]>();
    for (const e of ofKind) groups.set(title(e), [...(groups.get(title(e)) ?? []), e]);
    for (const [name, group] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
      out.push('', `### ${name}`);
      for (const e of group) {
        out.push('', kind === 'skill' ? `Level ${e.level}: ${stripSkillPrefix(e.text)}` : e.text);
      }
    }
  }
  return out.join('\n') + '\n';
}
